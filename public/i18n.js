const LANG = (() => {
  const saved = localStorage.getItem('lang');
  if (saved && MESSAGES[saved]) return saved;
  const browser = (navigator.languages ?? [navigator.language]).map((l) => l.slice(0, 2));
  return browser.find((l) => MESSAGES[l]) ?? 'ca';
})();

function t(key, vars = {}) {
  const s = MESSAGES[LANG][key] ?? MESSAGES.en[key] ?? key;
  return typeof s === 'string' ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '') : s;
}

// Static markup: data-i18n sets text, data-i18n-aria sets aria-label, data-i18n-title sets title.
function translatePage() {
  document.documentElement.lang = LANG;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  const select = document.getElementById('lang');
  select.innerHTML = Object.entries(MESSAGES).map(([k, m]) => `<option value="${k}">${m._name}</option>`).join('');
  select.value = LANG;
  select.addEventListener('change', () => {
    localStorage.setItem('lang', select.value);
    location.reload(); // charts are built with translated series names; a reload is the simplest full re-render
  });
}
